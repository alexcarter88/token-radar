// Token Radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every protocol on the snapshot's watchlist (the floor, never a ceiling) plus every
// rankable pre-token protocol below that floor — the early radar. A protocol is pre-token when its
// record carries no token (no market cap, no CoinGecko id, no symbol). Protocols above the floor that
// the watchlist leaves out are not ranked: they are the wrapped, staked or bridged products of tokens
// that already trade, versioned pools, or protocols with a parent, and the watchlist's rule — not this
// entry's preference — leaves them out. Live-token protocols are kept apart and shown with the
// market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The multiple is not a flat guess: it is
// the median market-cap-to-TVL ratio of the live-token protocols in the same category, computed from
// this snapshot at run time, so a DEX is priced like a DEX and a lender like a lender. Categories with
// too few live comparables fall back to the whole market's median. The multiple is clamped so one
// outlier cannot carry the board.
//
//   categoryMultiple = median(mcap_usd / tvl_usd) over live-token protocols in the category
//                      (at least 3 comparables, else the market median; clamped to [0.02, 1.5])
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(tvl_usd x categoryMultiple x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row, and the same function
// in the dashboard recomputes every row the page shows.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

